#!/usr/bin/env python3
"""Build submissions/submissions.csv -- the version -> what-was-actually-shipped map.

Generated from each submission's own `.meta.json` sidecar (written by submit.py),
joined to the review tier in pipeline_catalog.csv. Hand-maintaining this table
would let it drift from the parquets it describes, which is the one thing an
index must not do -- so it is generated, like results.csv and pipeline_review.csv.

The `reproducible` column is the point of the join: an arm that has been
quarantined under overtuned/ is no longer in config.ARMS, and submit.py takes
`--arm` from `choices=list(config.ARMS)`. Those versions CANNOT be regenerated by
the current code. They are on the leaderboard; they are not rebuildable.

    python build_submission_index.py
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config

HERE = Path(__file__).resolve().parent
SUBS = HERE / "submissions"
OUT = SUBS / "submissions.csv"

VERSION_RE = re.compile(r"_v(?P<version>\d+)\.parquet\.meta\.json$")


def tier_map() -> dict:
    p = HERE / "pipeline_catalog.csv"
    if not p.exists():
        return {}
    with p.open(encoding="utf-8") as fh:
        return {r["pipeline"]: r.get("review_tier", "") for r in csv.DictReader(fh)}


def main() -> int:
    tiers = tier_map()
    live_arms = set(config.ARMS)
    rows = []

    for meta_path in SUBS.glob("*.parquet.meta.json"):
        m = VERSION_RE.search(meta_path.name)
        if not m:
            print(f"  (skip {meta_path.name}: no _v<N> in name)")
            continue
        j = json.loads(meta_path.read_text(encoding="utf-8"))
        arm = j.get("arm", "")
        # NOT with_suffix("") -- that strips only ONE suffix off
        # "<name>.parquet.meta.json" and yields "<name>.parquet.meta".
        parquet = meta_path.parent / meta_path.name[: -len(".meta.json")]
        prov = j.get("provenance", {}).get(arm, {})

        # A `full` run is the refit-on-everything surface the build is designed to
        # submit from; a `forward` run only ever saw Jan-Aug, so submitting one
        # ships a model trained on ~2/3 of the available data.
        split = j.get("split", "")
        trained_on = "full training period" if split == "full" else f"{split} split only"

        notes = []
        if arm not in live_arms:
            notes.append("arm quarantined under overtuned/ -- not in config.ARMS, "
                         "so submit.py can no longer rebuild this")
        if split != "full":
            notes.append("shipped WITHOUT the full-period refit (trained on the "
                         f"{split} split's train months only)")

        rows.append({
            "version": int(j.get("version", m.group("version"))),
            "file": parquet.name,
            "arm": arm,
            "review_tier": tiers.get(arm, ""),
            "split": split,
            "trained_on": trained_on,
            "featureset": j.get("featureset", ""),
            "outlier_policy": j.get("outlier_policy", ""),
            "seed": j.get("seed", ""),
            "tag": j.get("tag") or "",
            "reproducible": "yes" if arm in live_arms else "NO",
            "n_rows": j.get("n_rows", ""),
            "pred_mean": round(j["pred_mean"], 2) if j.get("pred_mean") is not None else "",
            "pred_median": round(j["pred_median"], 2) if j.get("pred_median") is not None else "",
            "prediction_cap_sec": j.get("prediction_cap_sec", ""),
            "feature_fingerprint": prov.get("feature_fingerprint", ""),
            "team": j.get("team", ""),
            "notes": "; ".join(notes),
        })

    rows.sort(key=lambda r: r["version"])
    cols = ["version", "file", "arm", "review_tier", "split", "trained_on",
            "featureset", "outlier_policy", "seed", "tag", "reproducible",
            "n_rows", "pred_mean", "pred_median", "prediction_cap_sec",
            "feature_fingerprint", "team", "notes"]

    tmp = OUT.with_suffix(".csv.tmp")
    with tmp.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    tmp.replace(OUT)

    print(f"wrote {OUT} ({len(rows)} submissions)")
    for r in rows:
        flag = "" if r["reproducible"] == "yes" else "   <-- NOT REBUILDABLE"
        print(f"  v{r['version']:<3} [{r['review_tier'] or '?'}] {r['arm']:32s} "
              f"{r['split']:8s} seed{r['seed']}{flag}")

    n_bad = sum(1 for r in rows if r["reproducible"] != "yes")
    n_noref = sum(1 for r in rows if r["split"] != "full")
    if n_bad:
        print(f"\n  [WARN] {n_bad}/{len(rows)} submissions were built from arms now "
              f"quarantined as over-tuned (see overtuned/README.md).")
    if n_noref:
        print(f"  [WARN] {n_noref}/{len(rows)} submissions skipped the full-period "
              f"refit and shipped a model trained on the forward split only.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
