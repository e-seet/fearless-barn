# ---------------------------------------------------------------------------
# Feature-code provenance stamp.
#
# Closing-gate finding: config.feature_code_fingerprint() keyed the FEATURE
# CACHE (design-gate S6) but nothing keyed the RUNS, so a compare could -- and
# did -- rank a 131-feature old-code ridge against a 57-feature new-code
# LightGBM and call the difference "method". n_features caught it here only by
# luck: a change that alters feature VALUES without changing the count would
# have been completely invisible.
#
# The stamp is injected here, in the one write path every arm already funnels
# through, rather than in each train.py -- both because a per-arm copy is how
# arms drift apart, and because this build does not own every pipeline folder
# (the *_antigravity arms are third-party) yet the gate must cover them or it
# proves nothing. Any JSON payload that is a dict carrying "featureset" is a
# run artifact whose contents depend on features.py; it gets the stamp.
# ---------------------------------------------------------------------------
_write_json_guarded_raw = write_json_guarded


def write_json_guarded(path, payload, **kwargs):  # noqa: F811 - deliberate wrapper
    """``ml_common.write_json_guarded`` plus the feature-code fingerprint stamp."""
    if isinstance(payload, dict) and "featureset" in payload             and "feature_fingerprint" not in payload:
        import config as _config
        payload = dict(payload)
        payload["feature_fingerprint"] = _config.feature_code_fingerprint()
    return _write_json_guarded_raw(path, payload, **kwargs)


