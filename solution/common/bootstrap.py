"""Bootstrap: locate the workspace root and re-export ml_common's Mode 2 checks.

Generated by tools/new_mode2.py -- do not hand-edit the workspace-root resolution
below. It walks UP from THIS FILE's own location until it finds a directory that
contains tools/ml_common, and inserts that directory's tools/ onto sys.path. This is
deliberate: a hardcoded absolute path to the workspace breaks the moment this solution
folder is moved, copied, or run from a different machine (MISTAKES.md #12).

Import this module instead of importing ml_common directly, e.g.:

    from common.bootstrap import seed_everything, triage, run_dir

so every pipeline in this solution folder resolves the workspace the same way.
"""
from __future__ import annotations

import sys
from pathlib import Path


def _find_workspace_root(start: Path) -> Path:
    """Walk UP from ``start`` until a directory containing tools/ml_common is found.

    Raises RuntimeError naming exactly what it looked for and where, rather than
    failing with an opaque ImportError several lines later -- a solution folder that
    has been copied outside the workspace (or the workspace's tools/ml_common package
    itself renamed/missing) should fail here, at the first import, with a clear cause.
    """
    here = start.resolve()
    for candidate in [here, *here.parents]:
        if (candidate / "tools" / "ml_common").is_dir():
            return candidate
    raise RuntimeError(
        "common/bootstrap.py could not locate the workspace root by walking up from "
        "{}. Looked for a directory containing 'tools/ml_common' in this path and "
        "every parent of it, and found none. This solution folder must live inside "
        "(or be reachable by walking up from) the claudekaggle workspace for "
        "tools/ml_common to be importable -- it cannot be used standalone outside "
        "the workspace.".format(start)
    )


WORKSPACE_ROOT = _find_workspace_root(Path(__file__).resolve().parent)
_TOOLS_DIR = str(WORKSPACE_ROOT / "tools")
if _TOOLS_DIR not in sys.path:
    sys.path.insert(0, _TOOLS_DIR)

